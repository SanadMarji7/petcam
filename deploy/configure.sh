#!/usr/bin/env bash
# One-time setup for a Petcam server.
#
#   ./configure.sh example.com
#
# It fills <domain> into caddy.yaml and livekit.yaml, generates random keys
# and writes petcam.env. Run it in the deploy/ directory of a full checkout of
# the repository on the VPS (git clone, as in DEPLOY.md): docker compose
# builds the petcam image from the repository root, so copying only deploy/
# to the server is not enough. If you prefer to run it on your laptop, copy
# the resulting petcam.env, caddy.yaml and livekit.yaml into the deploy/
# directory of the checkout on the VPS. It refuses to overwrite an existing
# petcam.env so keys never change by accident (changing them invalidates
# every QR code already scanned).
set -euo pipefail

cd "$(dirname "$0")"

domain="${1:-}"
if [ -z "$domain" ]; then
    echo "Usage: ./configure.sh <domain>      e.g.  ./configure.sh example.com" >&2
    echo "The server will be reachable as app.<domain>, lk.<domain> and turn.<domain>." >&2
    exit 1
fi
# Lower-case letters, digits, dots and dashes only: that is a valid DNS name
# and also guarantees the value is safe to paste into sed below.
if ! printf '%s' "$domain" | /usr/bin/grep -Eq '^[a-z0-9]([a-z0-9-]*[a-z0-9])?(\.[a-z0-9]([a-z0-9-]*[a-z0-9])?)+$'; then
    echo "'$domain' does not look like a domain (use lower-case letters, digits, dots and dashes, e.g. example.com)." >&2
    exit 1
fi

if [ -e petcam.env ]; then
    echo "petcam.env already exists, keeping its keys. Delete it first if you really want new ones." >&2
    exit 1
fi

random_hex() {
    # 32 random bytes as 64 hex characters. openssl is on every Ubuntu
    # install; python3 is the fallback.
    if command -v openssl >/dev/null 2>&1; then
        openssl rand -hex 32
    else
        python3 -c 'import secrets; print(secrets.token_hex(32))'
    fi
}

publisher_key="$(random_hex)"
viewer_key="$(random_hex)"
livekit_api_key="API$(random_hex | cut -c1-16)"
livekit_api_secret="$(random_hex)"

# Fill in the domain. The files keep working if the placeholder is already
# gone (for example after running this script once with the same domain).
for f in caddy.yaml livekit.yaml; do
    if /usr/bin/grep -q '<domain>' "$f"; then
        sed -i "s/<domain>/$domain/g" "$f"
        echo "Filled $domain into $f"
    else
        echo "$f already has a domain filled in; check it by hand if it is not $domain" >&2
    fi
done

umask 077   # petcam.env is readable by its owner only
cat > petcam.env <<ENV
# Generated by configure.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ). Keep this file private.
# See petcam.env.example for what every line means.
PETCAM_HOSTNAME=app.$domain
PETCAM_PUBLISHER_KEY=$publisher_key
PETCAM_VIEWER_KEY=$viewer_key
PETCAM_LIVEKIT_URL=wss://lk.$domain
PETCAM_LIVEKIT_API_KEY=$livekit_api_key
PETCAM_LIVEKIT_API_SECRET=$livekit_api_secret
LIVEKIT_KEYS=$livekit_api_key: $livekit_api_secret
PETCAM_MAX_VIEWERS=4
PETCAM_ROOM_NAME=petcam
PETCAM_PORT=8000
ENV

echo
echo "Wrote petcam.env with fresh random keys."
echo "Next: make sure DNS for app.$domain, lk.$domain and turn.$domain points at this server,"
echo "then run:  docker compose up -d --build"
