#!/usr/bin/env python3
"""
Petcam Interactive Setup Assistant & QR Code Generator
Automates configuration, generates cryptographic keys, detects Tailscale MagicDNS,
and displays instant scannable QR codes in your terminal for one-tap device pairing.
"""
from __future__ import annotations

import json
import os
import secrets
import subprocess
import sys
from pathlib import Path

# Add QR code generator support: try 'qrcode' package, or fallback to URL and clean ASCII box
try:
    import qrcode  # type: ignore[import-not-found]
    HAS_QRCODE_PKG = True
except ImportError:
    HAS_QRCODE_PKG = False


def print_banner() -> None:
    print("\033[1;36m")
    print("=" * 64)
    print("   🐶  PETCAM — SELF-HOSTED WEBRTC DOG MONITOR SETUP WIZARD  🐶")
    print("=" * 64)
    print("\033[0m")


def detect_tailscale_hostname() -> str:
    """Attempts to auto-detect Tailscale MagicDNS name using tailscale CLI."""
    try:
        output = subprocess.check_output(["tailscale", "status", "--json"], text=True, stderr=subprocess.DEVNULL)
        data = json.loads(output)
        self_node = data.get("Self", {})
        dns_name = self_node.get("DNSName", "")
        if dns_name:
            # Strip trailing dot if present
            return dns_name.rstrip(".")
    except Exception:
        pass

    try:
        ip = subprocess.check_output(["tailscale", "ip", "-4"], text=True, stderr=subprocess.DEVNULL).strip()
        if ip:
            return f"dogcam.{ip}.ts.net"
    except Exception:
        pass

    return "dogcam.your-tailnet.ts.net"


def render_terminal_qr(data_url: str, label: str) -> None:
    """Renders QR code in terminal using ANSI blocks if qrcode installed, or neat URL box."""
    print(f"\n\033[1;33m>>> {label}\033[0m")
    print(f"\033[1;32mPairing URL: {data_url}\033[0m\n")

    if HAS_QRCODE_PKG:
        qr = qrcode.QRCode(border=1)
        qr.add_data(data_url)
        qr.make(fit=True)
        # Print using ANSI inverted blocks
        matrix = qr.get_matrix()
        for row in matrix:
            line = "".join("  " if col else "\033[7m  \033[0m" for col in row)
            print(line)
        print()
    else:
        print("  \033[90mTip: Run 'pip install qrcode' to display graphical QR codes in this terminal.\033[0m")


def main() -> None:
    print_banner()

    config_path = Path("config.toml")
    detected_host = detect_tailscale_hostname()

    if config_path.exists():
        print("\033[1;32m[✓] Existing config.toml found.\033[0m Loading configuration...")
        import config
        try:
            settings = config.load_settings()
            hostname = settings.hostname
            publisher_key = settings.publisher_key
            viewer_key = settings.viewer_key
        except Exception as e:
            print(f"\033[1;31m[!] Error parsing config.toml: {e}\033[0m")
            return
    else:
        print("\033[1;33m[*] Creating new config.toml with auto-generated secure keys...\033[0m")
        hostname = detected_host
        publisher_key = secrets.token_urlsafe(32)
        viewer_key = secrets.token_urlsafe(32)

        config_content = f"""# Petcam configuration file
# Auto-generated by setup.py

# Tailscale MagicDNS hostname
hostname = "{hostname}"

# Secret keys (32+ characters)
publisher_key = "{publisher_key}"
viewer_key = "{viewer_key}"

# Settings
max_viewers = 4
stun_enabled = false
port = 8000
"""
        with open(config_path, "w") as f:
            f.write(config_content)
        print(f"\033[1;32m[✓] Saved {config_path}\033[0m")

    # Construct secure one-tap pairing URLs (fragment-based, key never sent in HTTP headers)
    cam_pairing_url = f"https://{hostname}/cam#key={publisher_key}"
    watch_pairing_url = f"https://{hostname}/watch#key={viewer_key}"

    print("-" * 64)
    print("\033[1;37mONE-TAP DEVICE SETUP (NO MANUAL KEY TYPING REQUIRED):\033[0m")
    print("-" * 64)

    render_terminal_qr(cam_pairing_url, "1. IPAD SETUP (Scan with iPad Camera App)")
    print("   → Open camera app on iPad, point at QR code, tap the yellow Safari link.")
    print("   → Key is automatically saved; then tap Start Camera and turn on Guided Access.")

    render_terminal_qr(watch_pairing_url, "2. PIXEL / VIEWER SETUP (Scan with Phone Camera)")
    print("   → Point Pixel camera at QR code, tap the link to watch instantly.")
    print("   → In Chrome, tap 'Add to Home screen' for a full-screen app experience.")

    print("\n" + "=" * 64)
    print("\033[1;36mNEXT STEPS:\033[0m")
    print(f"1. Start Tailscale HTTPS proxy:")
    print(f"   \033[1;32msudo tailscale serve --bg https / http://127.0.0.1:8000\033[0m")
    print(f"2. Start or enable Petcam service:")
    print(f"   \033[1;32msudo systemctl enable --now dogcam\033[0m")
    print(f"   (or for development: uvicorn main:app --host 127.0.0.1 --port 8000)")
    print("=" * 64 + "\n")


if __name__ == "__main__":
    main()
